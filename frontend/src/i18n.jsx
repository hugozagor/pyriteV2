const DICTS = { fr, en, es, ru }
const STORAGE_KEY = 'pyrite_lang'

function initialLang() {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved && DICTS[saved]) return saved
  const nav = (navigator.language || 'fr').slice(0, 2)
  return DICTS[nav] ? nav : 'fr'
}

const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const l = initialLang()
    setLocale(l)   // sync the formatters before the first render
    setApiLang(l)
    return l
  })

  useEffect(() => {
    document.documentElement.setAttribute('lang', lang)
  }, [lang])

  const t = useCallback((key, vars) => {
    let s = (DICTS[lang] && DICTS[lang][key]) ?? DICTS.fr[key] ?? key
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k])
    return s
  }, [lang])

  // Translate a stored canonical category value for display.
  const tc = useCallback((value) => (DICTS[lang]?.[`cat.${value}`] ?? value), [lang])

  const setLang = useCallback((l) => {
    if (!DICTS[l]) return
    // Update the module-level locale + API language synchronously, BEFORE the
    // re-render: child page effects run before the provider effect, so doing
    // this here ensures listings refetch with the new language (no one-step lag).
    setLocale(l)
    setApiLang(l)
    localStorage.setItem(STORAGE_KEY, l)
    setLangState(l)
  }, [])

  return (
    <I18nContext.Provider value={{ lang, setLang, t, tc }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  return useContext(I18nContext)
}
